#!/usr/bin/env python3
"""Write THIRD-PARTY-NOTICES.md: every bundled component with its licence.

Run from the repository root after changing dependencies:
    python3 scripts/third-party.py
"""
import json
import subprocess

def rust():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--manifest-path", "src-tauri/Cargo.toml", "--filter-platform", "x86_64-unknown-linux-gnu"]))
    used = {node["id"] for node in meta["resolve"]["nodes"]}
    rows = {}
    for p in meta["packages"]:
        if p["id"] in used and p["name"] != "openwren":
            rows[(p["name"], p["version"])] = (p.get("license") or "see repository", p.get("repository") or "")
    return rows

def javascript():
    data = json.loads(subprocess.check_output(["pnpm", "licenses", "list", "--prod", "--json"]))
    rows = {}
    for licence, packages in data.items():
        for p in packages:
            for version in p.get("versions", [p.get("version", "")]):
                rows[(p["name"], version)] = (licence, p.get("homepage") or "")
    return rows

def table(rows):
    out = ["| Component | Version | Licence |", "|---|---|---|"]
    for (name, version), (licence, link) in sorted(rows.items(), key=lambda r: r[0][0].lower()):
        out.append(f"| {'[' + name + '](' + link + ')' if link else name} | {version} | {licence} |")
    return "\n".join(out)

r, j = rust(), javascript()
text = f"""# Third-party notices

OpenWren is licensed under the Apache License 2.0 (see [LICENSE](LICENSE)). It is built from, and its packages contain, the components below. Each remains under its own licence, whose full text is in the linked repository.

This file is generated by `scripts/third-party.py`. Do not edit it by hand.

## Bundled assets

| Asset | Licence |
|---|---|
| [Inter](https://rsms.me/inter/) and [Nunito](https://github.com/googlefonts/nunito) fonts | SIL Open Font License 1.1 |
| [Tabler Icons](https://tabler.io/icons) | MIT |
| [Simple Icons](https://simpleicons.org) (logos of well-known senders) | CC0 1.0; each logo is a trademark of its owner |
| [SQLCipher](https://www.zetetic.net/sqlcipher/) (encrypted SQLite, compiled in) | BSD-3-Clause |

OpenSSL (Apache-2.0) is used from the system at run time and is not bundled.

## Rust crates ({len(r)})

{table(r)}

## JavaScript packages ({len(j)})

{table(j)}
"""
open("THIRD-PARTY-NOTICES.md", "w").write(text)
print(f"{len(r)} Rust crates and {len(j)} JavaScript packages listed")
